
require('dotenv').config();

const Database = require('better-sqlite3');
const { Client } = require('pg');
const path = require('path');

const sqlite = new Database(path.join(__dirname, 'masar.sqlite'), {
  readonly: true
});

const pg = new Client({
  connectionString: process.env.DATABASE_URL
});

const schemas = [
  `CREATE TABLE IF NOT EXISTS properties (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    title_ar TEXT NOT NULL DEFAULT '',
    description TEXT NOT NULL DEFAULT '',
    description_ar TEXT NOT NULL DEFAULT '',
    area TEXT NOT NULL,
    area_other TEXT NOT NULL DEFAULT '',
    market TEXT NOT NULL,
    category TEXT NOT NULL,
    property_type TEXT NOT NULL DEFAULT 'Apartment',
    price TEXT NOT NULL DEFAULT '',
    size TEXT NOT NULL DEFAULT '',
    bedrooms TEXT NOT NULL DEFAULT '',
    payment TEXT NOT NULL DEFAULT '',
    developer TEXT NOT NULL DEFAULT '',
    image_url TEXT NOT NULL DEFAULT '',
    images TEXT NOT NULL DEFAULT '[]',
    featured INTEGER NOT NULL DEFAULT 0,
    status TEXT NOT NULL DEFAULT 'active',
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
  )`,
  `CREATE TABLE IF NOT EXISTS leads (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    phone TEXT NOT NULL,
    email TEXT NOT NULL DEFAULT '',
    area TEXT NOT NULL DEFAULT '',
    area_other TEXT NOT NULL DEFAULT '',
    market TEXT NOT NULL DEFAULT '',
    category TEXT NOT NULL DEFAULT '',
    budget TEXT NOT NULL DEFAULT '',
    details TEXT NOT NULL DEFAULT '',
    property_id INTEGER REFERENCES properties(id) ON DELETE SET NULL,
    source TEXT NOT NULL DEFAULT 'interest form',
    status TEXT NOT NULL DEFAULT 'New',
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
  )`,
  `CREATE TABLE IF NOT EXISTS admins (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT UNIQUE NOT NULL,
    password_hash TEXT NOT NULL
  )`
];

async function main() {
  if (!process.env.DATABASE_URL) {
    throw new Error('DATABASE_URL is missing from .env');
  }

  console.log('Reading local database...');

  const properties = sqlite.prepare('SELECT * FROM properties ORDER BY id').all();
  const leads = sqlite.prepare('SELECT * FROM leads ORDER BY id').all();
  const admins = sqlite.prepare('SELECT * FROM admins ORDER BY id').all();

  console.log(`Local properties: ${properties.length}`);
  console.log(`Local leads: ${leads.length}`);
  console.log(`Local admins: ${admins.length}`);

  await pg.connect();

  for (const schema of schemas) {
    await pg.query(schema);
  }

  await pg.query('BEGIN');

  try {
    const tables = [
      {
        name: 'properties',
        rows: properties,
        columns: [
          'id', 'title', 'title_ar', 'description', 'description_ar',
          'area', 'area_other', 'market', 'category', 'property_type',
          'price', 'size', 'bedrooms', 'payment', 'developer',
          'image_url', 'images', 'featured', 'status', 'created_at'
        ]
      },
      {
        name: 'leads',
        rows: leads,
        columns: [
          'id', 'name', 'phone', 'email', 'area', 'area_other',
          'market', 'category', 'budget', 'details', 'property_id',
          'source', 'status', 'created_at'
        ]
      },
      {
        name: 'admins',
        rows: admins,
        columns: ['id', 'username', 'password_hash']
      }
    ];

    for (const table of tables) {
      for (const row of table.rows) {
        const columns = table.columns;
        const values = columns.map(column => row[column]);
        const placeholders = columns.map((_, i) => `$${i + 1}`).join(', ');
        const updates = columns
          .filter(column => column !== 'id')
          .map(column => `${column} = EXCLUDED.${column}`)
          .join(', ');

        const sql = `
          INSERT INTO ${table.name} (${columns.join(', ')})
          VALUES (${placeholders})
          ON CONFLICT (id) DO UPDATE SET ${updates}
        `;

        await pg.query(sql, values);
      }

      console.log(`Migrated ${table.name}: ${table.rows.length}`);
    }

    for (const table of ['properties', 'leads', 'admins']) {
      await pg.query(`
        SELECT setval(
          pg_get_serial_sequence('${table}', 'id'),
          COALESCE((SELECT MAX(id) FROM ${table}), 1),
          EXISTS (SELECT 1 FROM ${table})
        )
      `);
    }

    await pg.query('COMMIT');

    console.log('Migration completed successfully!');

    for (const table of ['properties', 'leads', 'admins']) {
      const result = await pg.query(`SELECT COUNT(*)::int AS count FROM ${table}`);
      console.log(`Neon ${table}: ${result.rows[0].count}`);
    }
  } catch (error) {
    await pg.query('ROLLBACK');
    throw error;
  }
}

main()
  .catch(error => {
    console.error('Migration failed:', error.message);
    process.exitCode = 1;
  })
  .finally(async () => {
    sqlite.close();
    if (pg._connected) await pg.end();
  });
